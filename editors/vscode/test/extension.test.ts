function cli(args: string[], input?: string): any {
  return JSON.parse(execFileSync(executable, ['--repo', root, '--json', '--author', 'agent', ...args], { env: process.env, input, encoding: 'utf8' }));
}
async function eventually<T>(fn: () => Promise<T | undefined>): Promise<T> {
  let error: unknown;
  for (let i = 0; i < 60; i++) {
    try { const value = await fn(); if (value) return value; } catch (e) { error = e; }
    await new Promise(resolve => setTimeout(resolve, 200));
  }
  throw error || new Error('Timed out waiting for VS Code UI');
}
